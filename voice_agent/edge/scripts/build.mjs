// Packs the company files into the Worker, and copies the voice-detection files and the page into public/.

import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const edge = join(dirname(fileURLToPath(import.meta.url)), "..");
const company = join(edge, "..", "..", "company");

const names = readdirSync(company).filter(name => name.endsWith(".md") && name !== "README.md");
const files = Object.fromEntries(names.map(name => [name, readFileSync(join(company, name), "utf8").replace(/\r\n/g, "\n")]));

// Replies use a shorter plans file. The spoken summary already holds price, data, minutes, and validity.
const DROP = ["- ID:", "- Category:", "- Price:", "- Data:", "- Minutes:", "- Validity:", "- Network:"];
const replyFiles = { ...files, "plans.md": files["plans.md"].split("\n").filter(line => !DROP.some(prefix => line.startsWith(prefix))).join("\n") };

const topics = {
  files: Object.fromEntries(names.filter(name => name !== "faq.md").map(name => [name, [...files[name].matchAll(/^#{1,2} (.+)$/gm)].map(match => match[1])])),
  account_data: "Customer account records (balance, data use, bills, tickets, and orders) are available once the caller passes identity checks.",
};
const readJson = name => JSON.parse(readFileSync(join(company, name), "utf8"));
const records = readJson("orders_and_tickets.json");
const data = { files, replyFiles, topics, customers: readJson("customers.json").customers, tickets: records.tickets, orders: records.orders };
writeFileSync(join(edge, "src", "kb.generated.js"), `// Generated by scripts/build.mjs. Edit the files in company/ instead.\nexport const COMPANY = ${JSON.stringify(data)};\n`);

const vendor = join(edge, "public", "vendor");
mkdirSync(vendor, { recursive: true });
const vad = join(edge, "node_modules", "@ricky0123", "vad-web", "dist");
const ort = join(edge, "node_modules", "onnxruntime-web", "dist");
for (const name of ["bundle.min.js", "vad.worklet.bundle.min.js", "silero_vad_legacy.onnx"]) copyFileSync(join(vad, name), join(vendor, name));
for (const name of ["ort.wasm.min.js", "ort-wasm-simd-threaded.wasm", "ort-wasm-simd-threaded.mjs"]) copyFileSync(join(ort, name), join(vendor, name));
console.log(`Packed ${names.length} knowledge files and ${data.customers.length} customers.`);
